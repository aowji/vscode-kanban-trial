import assert from 'node:assert/strict';
import { test } from 'node:test';
import {
  addBoardList,
  boardFileTemplate,
  clearBoardList,
  isBoardFile,
  minimalEdit,
  moveBoardList,
  normalizeTags,
  readBoard,
  removeBoardList,
  renameListTag,
  setBoardInclude,
  setCardTags,
  toCardKey,
} from '../src/core/store';

/** Tags of the `lists:` entries, i.e. the column names. */
const listTags = (text: string): string[] | undefined =>
  readBoard(text).lists?.map((list) => list.tag);

test('isBoardFile matches only the board suffixes', () => {
  assert.equal(isBoardFile('kanban.kb.yaml'), true);
  assert.equal(isBoardFile('C:/x/Board.KB.YML'), true);
  assert.equal(isBoardFile('notes.md'), false);
  assert.equal(isBoardFile('kanban.yaml'), false);
});

test('toCardKey strips ./ and backslashes', () => {
  assert.equal(toCardKey('./docs\\a.md'), 'docs/a.md');
  assert.equal(toCardKey('/docs/a.md'), 'docs/a.md');
});

test('readBoard reads the cards mapping', () => {
  const board = readBoard('version: 1\ncards:\n  docs/a.md:\n    tags:\n      - todo\n      - bug\n');
  assert.equal(board.error, undefined);
  assert.deepEqual(board.cardTags.get('docs/a.md'), ['todo', 'bug']);
});

test('readBoard tolerates hand-written entry shapes', () => {
  const board = readBoard(
    [
      'cards:',
      '  a.md:',
      '    tags: "todo, bug"',
      '  b.md:',
      '    - review',
      '  c.md:',
      '  d.md: {}',
      '',
    ].join('\n'),
  );
  assert.deepEqual(board.cardTags.get('a.md'), ['todo', 'bug']);
  assert.deepEqual(board.cardTags.get('b.md'), ['review']);
  assert.deepEqual(board.cardTags.get('c.md'), []);
  assert.deepEqual(board.cardTags.get('d.md'), []);
});

test('readBoard treats an empty or card-less file as empty', () => {
  assert.equal(readBoard('').cardTags.size, 0);
  assert.equal(readBoard('# only a comment\n').cardTags.size, 0);
  assert.equal(readBoard('version: 1\n').cardTags.size, 0);
});

test('readBoard reports broken YAML instead of throwing', () => {
  const board = readBoard('cards:\n  a.md: [unclosed\n');
  assert.match(board.error ?? '', /Invalid board file/);
  assert.equal(board.cardTags.size, 0);
});

test('readBoard reads the board-owned lists as plain tags', () => {
  const board = readBoard(
    ['version: 1', 'lists:', '  - todo', '  - in-progress', 'cards: {}', ''].join('\n'),
  );
  assert.deepEqual(
    board.lists?.map((list) => [list.id, list.tag]),
    [
      ['todo', 'todo'],
      ['in-progress', 'in-progress'],
    ],
  );
  assert.equal(board.error, undefined);
});

test('readBoard accepts {tag} / {name} list objects and ignores malformed entries', () => {
  const board = readBoard(
    ['lists:', '  - tag: todo', '  - name: done', '  - 42', '  - null', ''].join('\n'),
  );
  assert.deepEqual(board.lists?.map((list) => list.tag), ['todo', 'done', '42']);
});

test('readBoard distinguishes missing lists from an explicit empty list', () => {
  assert.equal(listTags('version: 1\ncards: {}\n'), undefined);
  assert.deepEqual(listTags('version: 1\nlists: []\n'), []);
});

test('normalizeTags accepts sequences, comma lists and scalars', () => {
  assert.deepEqual(normalizeTags(['todo', ' Bug ', 'todo']), ['todo', 'Bug']);
  assert.deepEqual(normalizeTags('todo, bug'), ['todo', 'bug']);
  assert.deepEqual(normalizeTags(undefined), []);
});

test('setCardTags fills an empty board file', () => {
  const update = setCardTags('', 'docs/a.md', ['todo']);
  assert.equal(update.changed, true);
  assert.equal(update.text, 'version: 1\ncards:\n  docs/a.md:\n    tags:\n      - todo\n');
});

test('setCardTags keeps existing cards and comments intact', () => {
  const before = [
    '# generated by Markdown Kanban — keep it in source control',
    'version: 1',
    'cards:',
    '  docs/a.md:',
    '    tags:',
    '      - backlog',
    '  other.md:',
    '    tags:',
    '      - done',
    '',
  ].join('\n');

  const update = setCardTags(before, 'docs/a.md', ['todo', 'bug']);
  assert.equal(
    update.text,
    [
      '# generated by Markdown Kanban — keep it in source control',
      'version: 1',
      'cards:',
      '  docs/a.md:',
      '    tags:',
      '      - todo',
      '      - bug',
      '  other.md:',
      '    tags:',
      '      - done',
      '',
    ].join('\n'),
  );
  // The edit only touches the changed lines, not the whole file.
  assert.ok(update.end - update.start < before.length);
  assert.equal(
    before.slice(0, update.start) + update.newText + before.slice(update.end),
    update.text,
  );
});

test('setCardTags removes the entry when the tags are cleared', () => {
  const update = setCardTags('version: 1\ncards:\n  a.md:\n    tags:\n      - todo\n', 'a.md', []);
  assert.equal(update.text, 'version: 1\ncards: {}\n');
});

test('setCardTags is a no-op when nothing changes', () => {
  const before = 'version: 1\ncards:\n  a.md:\n    tags:\n      - todo\n';
  const update = setCardTags(before, 'a.md', ['todo']);
  assert.equal(update.changed, false);
  assert.equal(update.text, before);
});

test('setCardTags normalizes other spellings even when the tags match', () => {
  // This asymmetry is why the editor skips a drop onto the card's own column:
  // without that guard a hand-written `tags: [todo]` would be reformatted.
  const flow = setCardTags('version: 1\ncards:\n  a.md:\n    tags: [todo]\n', 'a.md', ['todo']);
  assert.equal(flow.changed, true);
  assert.equal(flow.text, 'version: 1\ncards:\n  a.md:\n    tags:\n      - todo\n');

  const comma = setCardTags('version: 1\ncards:\n  a.md:\n    tags: "todo"\n', 'a.md', ['todo']);
  assert.equal(comma.changed, true);
});

test('setCardTags refuses to rewrite a broken board file', () => {
  assert.throws(() => setCardTags('cards:\n  a.md: [unclosed\n', 'a.md', ['todo']), /Invalid board file/);
});

test('minimalEdit narrows a whole-file change to the diff', () => {
  assert.deepEqual(minimalEdit('abcXYdef', 'abcZZdef'), { start: 3, end: 5, newText: 'ZZ' });
  assert.deepEqual(minimalEdit('abc', 'abcd'), { start: 3, end: 3, newText: 'd' });
});

test('boardFileTemplate writes the board lists and round-trips', () => {
  const template = boardFileTemplate(['backlog', 'in-progress', 'done']);
  assert.ok(template.includes('lists:\n  - backlog\n  - in-progress\n  - done\n'));

  const board = readBoard(template);
  assert.equal(board.error, undefined);
  assert.deepEqual(board.lists?.map((list) => list.tag), ['backlog', 'in-progress', 'done']);
  assert.equal(board.cardTags.size, 0);
});

test('boardFileTemplate quotes tags that need it', () => {
  const template = boardFileTemplate(['#inbox']);
  assert.ok(template.includes('  - "#inbox"'));
  assert.deepEqual(listTags(template), ['#inbox']);
});

test('boardFileTemplate keeps tags that look like other YAML scalars', () => {
  const tags = ['true', 'null', '123', '- x', 'a: b', '#inbox'];
  assert.deepEqual(listTags(boardFileTemplate(tags)), tags);
});

test('boardFileTemplate defaults to no custom lists (No status only)', () => {
  const template = boardFileTemplate();
  assert.ok(template.includes('lists: []'));
  assert.ok(template.includes('include: []'));
  assert.deepEqual(listTags(template), []);
});

test('readBoard reads the include globs and tolerates a bare string', () => {
  assert.deepEqual(readBoard('include:\n  - docs/**/*.md\n  - notes/**\n').include, [
    'docs/**/*.md',
    'notes/**',
  ]);
  assert.deepEqual(readBoard('include: docs/**/*.md\n').include, ['docs/**/*.md']);
  assert.deepEqual(readBoard('version: 1\n').include, []);
});

test('setBoardInclude writes the key and removes it when the globs are cleared', () => {
  const start = '# keep me\nversion: 1\ninclude:\n  - old/**\nlists:\n  - todo\ncards: {}\n';
  const written = setBoardInclude(start, ['docs/**/*.md', 'notes/**']);
  assert.equal(written.changed, true);
  assert.ok(written.text.includes('# keep me'));
  assert.deepEqual(readBoard(written.text).include, ['docs/**/*.md', 'notes/**']);
  assert.deepEqual(listTags(written.text), ['todo']);

  assert.equal(setBoardInclude(written.text, ['docs/**/*.md', 'notes/**']).changed, false);

  const cleared = setBoardInclude(written.text, []);
  assert.ok(!cleared.text.includes('include:'));
  assert.deepEqual(readBoard(cleared.text).include, []);
  assert.deepEqual(listTags(cleared.text), ['todo']);

  // Patterns starting with glob characters must round-trip as quoted scalars.
  assert.deepEqual(readBoard(setBoardInclude('version: 1\n', ['*.md']).text).include, ['*.md']);
});

test('addBoardList appends a list and rejects duplicates', () => {
  const start = 'version: 1\nlists: []\ncards:\n  a.md:\n    tags:\n      - bug\n';
  const added = addBoardList(start, 'todo');
  assert.equal(added.changed, true);
  assert.deepEqual(listTags(added.text), ['todo']);
  assert.deepEqual(readBoard(added.text).cardTags.get('a.md'), ['bug']);

  const second = addBoardList(added.text, 'in-progress');
  assert.deepEqual(listTags(second.text), ['todo', 'in-progress']);

  assert.throws(() => addBoardList(second.text, 'TODO'), /already exists/i);
  assert.throws(() => addBoardList(second.text, '   '), /empty/i);
  assert.throws(() => addBoardList(second.text, '__unassigned'), /reserved/i);
});

test('addBoardList inserts at the requested position', () => {
  const start = 'version: 1\nlists:\n  - todo\n  - done\ncards: {}\n';

  const first = addBoardList(start, 'backlog', { index: 0 });
  assert.deepEqual(listTags(first.text), ['backlog', 'todo', 'done']);

  const middle = addBoardList(first.text, 'review', { index: 2 });
  assert.deepEqual(listTags(middle.text), ['backlog', 'todo', 'review', 'done']);

  const end = addBoardList(middle.text, 'archive', { index: 99 });
  assert.deepEqual(listTags(end.text), ['backlog', 'todo', 'review', 'done', 'archive']);
});

test('addBoardList seeds lists from the fallback when the key is missing', () => {
  const update = addBoardList('version: 1\ncards: {}\n', 'wip', {
    index: 1,
    fallbackLists: ['todo', 'done'],
  });
  assert.deepEqual(listTags(update.text), ['todo', 'wip', 'done']);
});

test('moveBoardList reorders lists without touching cards', () => {
  const start = [
    'version: 1',
    'lists:',
    '  - backlog',
    '  - todo',
    '  - review',
    '  - done',
    'cards:',
    '  a.md:',
    '    tags:',
    '      - review',
    '',
  ].join('\n');

  const moved = moveBoardList(start, 'review', 0);
  assert.equal(moved.changed, true);
  assert.deepEqual(listTags(moved.text), ['review', 'backlog', 'todo', 'done']);
  assert.deepEqual(readBoard(moved.text).cardTags.get('a.md'), ['review']);

  const toEnd = moveBoardList(moved.text, 'review', 99);
  assert.deepEqual(listTags(toEnd.text), ['backlog', 'todo', 'done', 'review']);
});

test('moveBoardList is a no-op for the same position or an unknown list', () => {
  const start = 'version: 1\nlists:\n  - todo\n  - done\ncards: {}\n';
  assert.equal(moveBoardList(start, 'todo', 0).changed, false);
  assert.equal(moveBoardList(start, 'missing', 1).changed, false);
  assert.equal(moveBoardList('version: 1\ncards: {}\n', 'todo', 0).changed, false);
});

test('removeBoardList removes the list without touching cards', () => {
  const start = [
    'version: 1',
    'lists:',
    '  - todo',
    '  - done',
    'cards:',
    '  a.md:',
    '    tags:',
    '      - todo',
    '      - bug',
    '',
  ].join('\n');
  const removed = removeBoardList(start, 'todo');
  assert.equal(removed.changed, true);
  assert.deepEqual(listTags(removed.text), ['done']);
  assert.deepEqual(readBoard(removed.text).cardTags.get('a.md'), ['todo', 'bug']);

  const empty = removeBoardList(removed.text, 'done');
  assert.deepEqual(listTags(empty.text), []);
});

test('clearBoardList removes the tag from every card shape', () => {
  const start = [
    'version: 1',
    'lists:',
    '  - todo',
    '  - done',
    'cards:',
    '  a.md:',
    '    tags:',
    '      - todo',
    '      - bug',
    '  b.md: "todo, bug"',
    '  c.md: todo',
    '  d.md:',
    '    tags:',
    '      - done',
    '',
  ].join('\n');
  const cleared = clearBoardList(start, 'todo');

  assert.equal(cleared.changed, true);
  // The list itself stays; only the cards lose the tag.
  assert.deepEqual(listTags(cleared.text), ['todo', 'done']);
  assert.deepEqual(readBoard(cleared.text).cardTags.get('a.md'), ['bug']);
  assert.deepEqual(readBoard(cleared.text).cardTags.get('b.md'), ['bug']);
  // A card with no other tag loses its entry, like setCardTags(..., []).
  assert.equal(readBoard(cleared.text).cardTags.has('c.md'), false);
  assert.deepEqual(readBoard(cleared.text).cardTags.get('d.md'), ['done']);
});

test('clearBoardList is inert for unknown or already-empty lists', () => {
  const start = 'version: 1\nlists:\n  - todo\ncards:\n  a.md:\n    tags:\n      - done\n';
  assert.equal(clearBoardList(start, 'nope').changed, false);
  assert.equal(clearBoardList(start, 'todo').changed, false);
  assert.equal(clearBoardList(start, '').changed, false);
});

test('clearBoardList falls back to the configured lists', () => {
  const start = 'version: 1\ncards:\n  a.md:\n    tags:\n      - todo\n';
  const cleared = clearBoardList(start, 'todo', ['todo', 'done']);
  assert.deepEqual(listTags(cleared.text), undefined);
  assert.equal(readBoard(cleared.text).cardTags.size, 0);
});

test('renameListTag renames the tag on the list and on its cards', () => {
  const start = [
    'version: 1',
    'lists:',
    '  - todo',
    '  - done',
    'cards:',
    '  a.md:',
    '    tags:',
    '      - todo',
    '      - bug',
    '  b.md:',
    '    tags:',
    '      - done',
    '',
  ].join('\n');

  const renamed = renameListTag(start, 'todo', '待办');
  assert.equal(renamed.changed, true);
  assert.deepEqual(listTags(renamed.text), ['待办', 'done']);
  assert.deepEqual(readBoard(renamed.text).cardTags.get('a.md'), ['待办', 'bug']);
  // Other cards and their tags are untouched.
  assert.deepEqual(readBoard(renamed.text).cardTags.get('b.md'), ['done']);
});

test('renameListTag rewrites the other tolerated card shapes', () => {
  const start = [
    'version: 1',
    'lists: [todo]',
    'cards:',
    '  a.md:',
    '    - todo',
    '  b.md:',
    '    tags: "todo, bug"',
    '  c.md: todo',
    '',
  ].join('\n');

  const renamed = renameListTag(start, 'todo', 'wip');
  assert.deepEqual(readBoard(renamed.text).cardTags.get('a.md'), ['wip']);
  assert.deepEqual(readBoard(renamed.text).cardTags.get('b.md'), ['wip', 'bug']);
  assert.deepEqual(readBoard(renamed.text).cardTags.get('c.md'), ['wip']);
  assert.deepEqual(listTags(renamed.text), ['wip']);
});

test('renameListTag matches case-insensitively and can change case only', () => {
  const start = 'version: 1\nlists:\n  - todo\ncards:\n  a.md:\n    tags:\n      - TODO\n';
  const renamed = renameListTag(start, 'todo', 'Todo');
  assert.deepEqual(listTags(renamed.text), ['Todo']);
  assert.deepEqual(readBoard(renamed.text).cardTags.get('a.md'), ['Todo']);
});

test('renameListTag is inert for no-ops, unknown lists and empty names', () => {
  const start = 'version: 1\nlists:\n  - todo\ncards: {}\n';
  assert.equal(renameListTag(start, 'todo', 'todo').changed, false);
  assert.equal(renameListTag(start, 'missing', 'anything').changed, false);
  assert.throws(() => renameListTag(start, 'todo', '   '), /cannot be empty/);
});

test('renameListTag refuses to collide with another list', () => {
  const start = 'version: 1\nlists:\n  - todo\n  - done\ncards: {}\n';
  assert.throws(() => renameListTag(start, 'todo', 'DONE'), /already exists/i);
  assert.throws(() => renameListTag(start, 'todo', '__unassigned'), /reserved/i);
});

test('renameListTag seeds lists from the fallback when the key is missing', () => {
  const update = renameListTag('version: 1\ncards: {}\n', 'done', 'shipped', ['todo', 'done']);
  assert.deepEqual(listTags(update.text), ['todo', 'shipped']);
});

test('setCardTags preserves the lists section', () => {
  const before = 'version: 1\nlists:\n  - todo\n  - done\ncards: {}\n';
  const update = setCardTags(before, 'a.md', ['todo']);
  assert.equal(
    update.text,
    'version: 1\nlists:\n  - todo\n  - done\ncards:\n  a.md:\n    tags:\n      - todo\n',
  );
});
